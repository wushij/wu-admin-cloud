-- =============================================================================
-- add24 · 标准组织与岗位精简（补齐单体 add11 在微服务侧的缺口）
-- -----------------------------------------------------------------------------
-- 【背景】
--   单体侧通过 sql/migration/add11_standard_org_post.sql 把组织精简为 3 个标准部门
--   （总公司 / 研发部 / 运营部）、3 个黄金岗位（总经理 / 技术总监 / 研发工程师）。
--   单体的 admin_platform_dev.sql 中「扁平部门树 → 中心分级」的旧迁移代码已被 add11
--   接管并整段注释掉（注释写明：全新安装时 Part B 已写入 3 个标准部门，若继续执行旧迁移
--   会把新结构覆盖回旧结构）。
--
--   微服务迁移时误将那段已注释的旧迁移「解注释」照搬进 sql/01_wu_system.sql，
--   导致全新安装的库被写入 15 部门的旧组织树（本部→4 个中心→9 个部门→2 个组）与
--   19 岗位的旧岗位体系，与单体的标准组织结构不一致。
--
-- 【本脚本作用】
--   供已初始化的存量库执行，把组织与岗位回收到与单体 add11 一致的标准结构。
--   新环境直接执行 sql/01_wu_system.sql 即可（已内联标准结构，无需本脚本）。
--
-- 【幂等性】
--   可重复执行：每次先把用户部门归位到标准节点，再重建部门与岗位，最后重绑岗位。
--
-- 【依赖】
--   MySQL 8.0+；在 wu_system 库内执行。
-- =============================================================================

USE `wu_system`;
SET NAMES utf8mb4;

-- -----------------------------------------------------------------------------
-- 1. 用户部门归位：不在标准节点内的用户先统一落到研发部(2)
-- -----------------------------------------------------------------------------
UPDATE `sys_user` SET `dept_id` = 2
WHERE `dept_id` IS NULL OR `dept_id` NOT IN (1, 2, 3);

-- admin 归属总公司(1)，zhangsan 归属研发部(2)
UPDATE `sys_user` SET `dept_id` = 1 WHERE `id` = 1;
UPDATE `sys_user` SET `dept_id` = 2 WHERE `id` = 2;

-- -----------------------------------------------------------------------------
-- 2. 组织管理（sys_dept）精简为 3 个标准部门
-- -----------------------------------------------------------------------------
DELETE FROM `sys_dept`;

INSERT INTO `sys_dept`
(`id`, `name`, `parent_id`, `ancestors`, `sort`, `status`, `leader_name`, `leader_user_id`, `deleted`)
VALUES
(1, '总公司', 0, '0', 1, 1, '管理员', 1, 0),
(2, '研发部', 1, '0,1', 1, 1, '张三', 2, 0),
(3, '运营部', 1, '0,1', 2, 1, NULL, NULL, 0);

ALTER TABLE `sys_dept` AUTO_INCREMENT = 4;

-- -----------------------------------------------------------------------------
-- 3. 岗位管理（sys_post）精简为 3 个黄金岗位
-- -----------------------------------------------------------------------------
DELETE FROM `sys_user_post`;
DELETE FROM `sys_post`;

INSERT INTO `sys_post`
(`id`, `parent_id`, `post_code`, `post_name`, `sort`, `status`, `remark`, `deleted`)
VALUES
(1, 0, 'ceo', '总经理', 1, 1, '企业最高经营管理负责人', 0),
(2, 1, 'cto', '技术总监', 2, 1, '技术与研发整体负责人', 0),
(3, 2, 'dev', '研发工程师', 3, 1, '核心开发与技术实现', 0);

ALTER TABLE `sys_post` AUTO_INCREMENT = 4;

-- -----------------------------------------------------------------------------
-- 4. 绑定核心用户岗位：admin → 总经理(1)，zhangsan → 研发工程师(3)
-- -----------------------------------------------------------------------------
INSERT INTO `sys_user_post` (`user_id`, `post_id`) VALUES
(1, 1),
(2, 3);

-- -----------------------------------------------------------------------------
-- 5. 校验：确认最终为 3 部门 / 3 岗位 / 2 条岗位绑定
-- -----------------------------------------------------------------------------
SELECT
    (SELECT COUNT(*) FROM `sys_dept` WHERE `deleted` = 0) AS 部门数,
    (SELECT COUNT(*) FROM `sys_post` WHERE `deleted` = 0) AS 岗位数,
    (SELECT COUNT(*) FROM `sys_user_post`)             AS 用户岗位绑定数;